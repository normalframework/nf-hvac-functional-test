'use strict';

// Writes static/js/demo-data.js: the page's demo mode fixture. The plan comes from the real planner run on
// examples/site-config.example.json (VAV step on), so the demo shows what this code would do, not a mock-up.
// `node scripts/build-demo.js --check` fails when the file is stale.

const fs = require('node:fs');
const path = require('node:path');
const { adminAction, createSession } = require('../lib/admin');

const ROOT = path.join(__dirname, '..');
const OUT = path.join(ROOT, 'static', 'js', 'demo-data.js');

function demoConfig() {
  const config = JSON.parse(fs.readFileSync(path.join(ROOT, 'examples', 'site-config.example.json'), 'utf8'));
  for (const step of config.plan.steps) {
    if (step.step_id === 'vav.max_cool') step.enabled = true;
  }
  config.vav_test.strategy = 'flush_point';
  return config;
}

async function build() {
  const session = createSession();
  session.options = { siteConfig: JSON.stringify(demoConfig()) };
  const preview = await adminAction(session, 'plan_preview', {});
  if (!preview.ok) throw new Error(`demo plan failed: ${preview.code}`);
  const weekdays = [0, 1, 2, 3, 4].map(() => ({
    timeValues: [
      { time: { hour: 7, minute: 0 }, value: { boolean: true } },
      { time: { hour: 18, minute: 0 }, value: { boolean: false } },
    ],
  }));
  const data = {
    site: { name: 'Demo site', tz: 'America/Chicago' },
    preview,
    trigger: {
      mode: 'dry_run',
      rule: { kind: 'monthly_last', weekday: 3, hour: 12, minute: 0, tz: 'America/Chicago', start_date: '2026-01-01' },
      windows: [[], [], [], [{ start: 600, end: 900 }], [], [], []],
      blackout: { schedule_uuid: 'demo-occupancy', block_when_occupied: false, block_on_special_event: true },
    },
    schedule: {
      schedule: {
        uuid: 'demo-occupancy',
        name: 'Building occupancy',
        defaultValue: { boolean: false },
        weeklySchedule: { days: [...weekdays, { timeValues: [] }, { timeValues: [] }] },
        specialEvents: [
          { name: 'Holiday shutdown', priority: 1, dateRange: { startDate: { year: 2026, month: 12, day: 24 }, endDate: { year: 2027, month: 1, day: 1 } }, timeValues: [] },
          { name: 'Holiday', priority: 2, date: { year: 2026, month: 11, day: 26 }, timeValues: [] },
        ],
      },
    },
    history: [
      { run_id: 'demo-0924', at: '2026-09-24T17:00:00Z', outcome: 'pass', live: false, reason: 'complete', steps: [['ahu.baseline', 5], ['ahu.recirc', 20], ['ahu.economizer', 20], ['vav.max_cool', 30], ['recovery', 10]] },
      { run_id: 'demo-1029', at: '2026-10-29T17:00:00Z', outcome: 'aborted', live: false, reason: 'interlock:mixed_air_low', steps: [['ahu.baseline', 5], ['ahu.recirc', 12], ['recovery', 10]] },
      { run_id: 'demo-1112', at: '2026-11-12T19:30:00Z', outcome: 'pass', live: false, reason: 'complete', steps: [['ahu.baseline', 5], ['ahu.recirc', 20], ['vav.max_cool', 30], ['recovery', 10]] },
      { run_id: '', at: '2026-11-26T18:00:00Z', outcome: 'skipped', live: false, reason: 'special_event:Holiday', steps: [] },
    ],
  };
  const body = JSON.stringify(data, null, 2);
  return [
    '// GENERATED by scripts/build-demo.js from examples/site-config.example.json. Do not edit by hand.',
    '(function (root, factory) {',
    "  if (typeof module === 'object' && module.exports) module.exports = factory();",
    '  else root.NfftDemoData = factory();',
    '})(globalThis, function () {',
    "  'use strict';",
    `  return ${body.split('\n').join('\n  ')};`,
    '});',
    '',
  ].join('\n');
}

async function main() {
  const text = await build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('demo: static/js/demo-data.js is stale; run node scripts/build-demo.js');
      return 1;
    }
    console.log('demo: up to date');
    return 0;
  }
  fs.writeFileSync(OUT, text);
  console.log(`demo: wrote ${path.relative(ROOT, OUT)}`);
  return 0;
}

module.exports = { build };

if (require.main === module) main().then((code) => process.exit(code));
