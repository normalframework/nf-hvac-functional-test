'use strict';

// Writes static/roles-223p.js: the 223P property patterns, units and Haystack markers of every role in
// vendor/roles/openfdd-roles.json, so the page matches 223P models with the same role names as Open-FDD.
// `node scripts/build-roles-223p.js --check` fails when the file is stale.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const SRC = path.join(ROOT, 'vendor', 'roles', 'openfdd-roles.json');
const OUT = path.join(ROOT, 'static', 'roles-223p.js');

/** The binding fields of a role's Haystack mapping (haystack.binding_rules in the roles file). */
function haystackOf(/** @type {any} */ h) {
  /** @type {Record<string, any>} */
  const out = { unit: h.unit || null, kind: h.kind || null };
  for (const k of ['classes', 'markers', 'alt_markers', 'custom_markers', 'optional', 'forbid', 'equip_markers', 'equip_forbid']) {
    out[k] = Array.isArray(h[k]) ? h[k] : [];
  }
  out.binding_scope = h.binding_scope || null;
  return out;
}

function build() {
  const vocab = JSON.parse(fs.readFileSync(SRC, 'utf8'));
  /** @type {Record<string, string>} */
  const lexicon = {};
  for (const [term, entry] of Object.entries(vocab.lexicon || {})) lexicon[term] = /** @type {any} */ (entry).token;
  const data = {
    vocabulary: vocab.vocabulary,
    version: vocab.version,
    lexicon,
    function_markers: (vocab.haystack && vocab.haystack.function_markers) || ['sensor', 'sp', 'cmd'],
    roles: vocab.roles.filter((/** @type {any} */ r) => r.grounding === 's223' || r.grounding === 'extension').map((/** @type {any} */ r) => ({
      role: r.role,
      s223: r.s223,
      unit: r.unit || null,
      writable: r.writable || 'never',
      haystack: r.haystack ? haystackOf(r.haystack) : null,
    })),
  };
  const body = JSON.stringify(data);
  return [
    '// GENERATED by scripts/build-roles-223p.js from vendor/roles/openfdd-roles.json. Do not edit by hand.',
    '(function (root, factory) {',
    "  if (typeof module === 'object' && module.exports) module.exports = factory();",
    '  else root.NfftRoles223p = factory();',
    '})(globalThis, function () {',
    "  'use strict';",
    `  return ${body};`,
    '});',
    '',
  ].join('\n');
}

function main() {
  const text = build();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('roles-223p: static/roles-223p.js is stale; run node scripts/build-roles-223p.js');
      return 1;
    }
    console.log('roles-223p: up to date');
    return 0;
  }
  fs.writeFileSync(OUT, text);
  console.log(`roles-223p: wrote ${path.relative(ROOT, OUT)}`);
  return 0;
}

module.exports = { build };

if (require.main === module) process.exit(main());
